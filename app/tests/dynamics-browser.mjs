import {control} from './controls.mjs';
import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch({headless: true, executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe'});
const page = await browser.newPage({viewport: {width: 1440, height: 1050}, acceptDownloads: true});
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto('http://127.0.0.1:8765');
  await page.waitForFunction(() => document.querySelector('#score-title').value === 'Duvet');
  await control(page,'#sample-picker').selectOption('lullaby');
  await page.waitForFunction(() => document.querySelector('#score-title').value === 'Lullaby');
  await control(page,'#event-dynamics').selectOption('soft');
  assert.equal(await page.locator('[data-event="m1-e1"].has-note.dynamic-soft').count(), 2);
  await control(page,'#note-dynamics').selectOption('strong');
  assert.equal(await page.locator('[data-event="m1-e1"].has-note.dynamic-strong').count(), 1);
  assert.equal(await page.locator('[data-event="m1-e1"].has-note.dynamic-soft').count(), 1);
  await control(page,'#undo').click();
  assert.equal(await page.locator('[data-event="m1-e1"].has-note.dynamic-soft').count(), 2);
  await control(page,'#redo').click();
  await control(page,'#event-dynamics').selectOption('normal');
  assert.equal(await control(page,'#note-dynamics').inputValue(), 'inherit');
  await control(page,'#note-dynamics').selectOption('strong');
  await control(page,'#unify-dynamics').click();
  assert.equal(await control(page,'#note-dynamics').inputValue(), 'inherit');
  const position = id => page.locator(`[data-event="${id}"].has-note`).first();
  await position('m1-e1').click();
  await position('m1-e3').click({modifiers: ['Shift']});
  assert.match(await control(page,'#range-status').textContent(), /已选 3 个位置/);
  assert.equal(await page.locator('.range-selection').count(), 2);
  await control(page,'#batch-dynamics').selectOption('soft');
  await control(page,'#apply-dynamics').click();
  const changed = await page.evaluate(() => JSON.parse(localStorage.getItem('tablens.workspace.v1')));
  assert.ok(changed.measures[0].events.slice(0, 3).every(e => e.notes.every(n=>n.dynamics === 'soft')));
  assert.equal(changed.measures[0].events[3].dynamics, undefined);
  assert.equal(changed.measures.flatMap(m => m.events).flatMap(e => e.notes).length, 20);
  await control(page,'#undo').click();
  assert.equal(await page.locator('[data-event="m1-e3"].dynamic-soft').count(), 0);
  await control(page,'#redo').click();
  await page.reload();
  await page.waitForFunction(() => document.querySelector('#score-title').value === 'Lullaby');
  assert.equal(await control(page,'#note-dynamics').inputValue(), 'soft');
  await control(page,'#note-dynamics').selectOption('strong');
  const downloadPromise = page.waitForEvent('download');
  await control(page,'#export-file').click();
  const download = await downloadPromise;
  await control(page,'#event-dynamics').selectOption('normal');
  await control(page,'#file-input').setInputFiles(await download.path());
  await page.waitForFunction(() => document.querySelector('#note-dynamics').value === 'strong');
  const signal = await page.evaluate(async () => {
    const {createGuitarInstrument} = await import('/guitar.js');
    const {Player} = await import('/playback.js');
    async function energy(volume) {
      const ctx = new OfflineAudioContext(2, 22050, 44100), guitar = createGuitarInstrument();
      await guitar.prepare(ctx, [{midi: [64], strings: [1]}]);
      guitar(ctx, 64, 0, 0.4, volume, 1);
      const output = await ctx.startRendering(), samples = output.getChannelData(0);
      return samples.reduce((sum, value) => sum + value * value, 0);
    }
    const soft = await energy(0.16 * 0.55), strong = await energy(0.16 * 1.35);
    const preview = [];
    const player = new Player(() => {}, (ctx, midi, when, duration, volume) => {preview.push(volume); return () => {};});
    player.context = {currentTime: 0}; player.audio = async () => player.context;
    await player.preview([64, 52], [1, 5], 'natural', ['strong', 'soft']); player.stop();
    return {ratio: strong / soft, previewRatio: preview[0] / preview[1]};
  });
  assert.ok(Math.abs(signal.ratio - (1.35 / 0.55) ** 2) < 0.01);
  assert.ok(Math.abs(signal.previewRatio - 1.35 / 0.55) < 1e-8);
  await page.screenshot({path: 'app/.runtime/tablens-dynamics.png', fullPage: true});
  assert.deepEqual(errors, []);
  console.log('PASS: mixed chord dynamics, Shift range, batch/undo, save/reopen, real audio level differences and preview levels.');
} finally { await browser.close(); }
